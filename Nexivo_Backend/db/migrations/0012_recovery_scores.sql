-- 0012_recovery_scores: Nexivo M2. One Personalized Recovery Score per
-- observation per scoring config. Rows are never replaced: scoring again with a
-- new config version adds rows, so every result stays traceable to its config.

CREATE TABLE recovery_scores (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  observation_id   BIGINT           NOT NULL,
  patient_id       BIGINT           NOT NULL,
  config_id        BIGINT           NOT NULL,
  composite        DOUBLE PRECISION NOT NULL,
  baseline         DOUBLE PRECISION,
  slope            DOUBLE PRECISION,
  expected         DOUBLE PRECISION NOT NULL,
  category         VARCHAR(10)      NOT NULL,
  limited_history  BOOLEAN          NOT NULL,
  computed_at      TIMESTAMPTZ      NOT NULL DEFAULT now(),

  CONSTRAINT recovery_scores_composite_check CHECK (composite BETWEEN 0 AND 100),
  CONSTRAINT recovery_scores_category_check CHECK (category IN ('normal', 'slower', 'attention')),
  -- The spec says observation_id is unique, but also that rescoring with a new
  -- config keeps the old rows; unique per (observation, config) satisfies both.
  CONSTRAINT recovery_scores_observation_config_key UNIQUE (observation_id, config_id),
  CONSTRAINT recovery_scores_observation_fkey FOREIGN KEY (observation_id)
    REFERENCES recovery_observations (id) ON DELETE CASCADE,
  CONSTRAINT recovery_scores_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE,
  CONSTRAINT recovery_scores_config_fkey FOREIGN KEY (config_id)
    REFERENCES scoring_configs (id)
);

CREATE INDEX idx_recovery_scores_patient ON recovery_scores (patient_id, config_id);

COMMENT ON TABLE recovery_scores IS
  'Nexivo: Personalized Recovery Score per observation and scoring config. Computed in the same transaction as the observation; scripts/recompute-scores.js adds rows for a newly activated config.';
COMMENT ON COLUMN recovery_scores.composite IS 'C = sum of weight x normalized value, 0-100 (100 = best).';
COMMENT ON COLUMN recovery_scores.baseline IS 'B = mean composite of the previous window_k observations; NULL when there are none.';
COMMENT ON COLUMN recovery_scores.slope IS 'Least-squares slope of composite vs day_post_op over the last window_k observations (points per day); NULL without a measurable trend.';
COMMENT ON COLUMN recovery_scores.expected IS 'E(day): expected composite on this day_post_op from the config''s recovery curve.';
COMMENT ON COLUMN recovery_scores.category IS 'normal | slower (Slower than expected) | attention (Requires attention).';
COMMENT ON COLUMN recovery_scores.limited_history IS 'Fewer than min_history earlier observations: the fixed limited-history bands decided the category.';
