-- 0009_recovery_observations: Nexivo M1. Append-only check-in history.
-- The app never updates or deletes a row. A correction is a new row whose
-- corrects_observation_id points at the version it replaces; the "latest version"
-- of an observation is a row that no other row corrects.

CREATE TABLE recovery_observations (
  id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id               BIGINT       NOT NULL,
  observed_at              TIMESTAMPTZ  NOT NULL,
  day_post_op              INTEGER      NOT NULL,
  pain                     SMALLINT     NOT NULL,
  mobility                 SMALLINT     NOT NULL,
  fatigue                  SMALLINT     NOT NULL,
  symptoms                 JSONB        NOT NULL DEFAULT '{}',
  doses_prescribed         INTEGER      NOT NULL DEFAULT 0,
  doses_taken              INTEGER      NOT NULL DEFAULT 0,
  notes                    TEXT,
  entered_by               BIGINT,
  source                   VARCHAR(10)  NOT NULL,
  corrects_observation_id  BIGINT,
  created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT recovery_observations_day_post_op_check CHECK (day_post_op >= 0),
  CONSTRAINT recovery_observations_pain_check CHECK (pain BETWEEN 0 AND 10),
  CONSTRAINT recovery_observations_mobility_check CHECK (mobility BETWEEN 0 AND 10),
  CONSTRAINT recovery_observations_fatigue_check CHECK (fatigue BETWEEN 0 AND 10),
  CONSTRAINT recovery_observations_symptoms_check CHECK (jsonb_typeof(symptoms) = 'object'),
  CONSTRAINT recovery_observations_doses_check
    CHECK (doses_prescribed >= 0 AND doses_taken >= 0 AND doses_taken <= doses_prescribed),
  CONSTRAINT recovery_observations_source_check CHECK (source IN ('patient', 'clinician', 'import')),
  -- Each version can be corrected once, so the versions of one observation form a single chain.
  CONSTRAINT recovery_observations_corrects_key UNIQUE (corrects_observation_id),
  CONSTRAINT recovery_observations_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE,
  CONSTRAINT recovery_observations_entered_by_fkey FOREIGN KEY (entered_by)
    REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT recovery_observations_corrects_fkey FOREIGN KEY (corrects_observation_id)
    REFERENCES recovery_observations (id)
);

-- History reads: one patient's observations in time order.
CREATE INDEX idx_recovery_observations_patient_time ON recovery_observations (patient_id, observed_at, id);

COMMENT ON TABLE recovery_observations IS
  'Nexivo: append-only check-in history. Never UPDATEd or DELETEd by the app; corrections insert a new row.';
COMMENT ON COLUMN recovery_observations.day_post_op IS
  'Whole days from recovery_profiles.surgery_date to observed_at (UTC calendar dates), computed on insert.';
COMMENT ON COLUMN recovery_observations.mobility IS
  '0-10 where 10 is fully mobile (higher is better, unlike pain and fatigue).';
COMMENT ON COLUMN recovery_observations.symptoms IS
  'Severity per symptom, 0-3 (none/mild/moderate/severe). Keys come from the scoring config''s symptoms list; all are stored, missing ones as 0.';
COMMENT ON COLUMN recovery_observations.entered_by IS
  'users.id of the patient who entered it. NULL for clinician entries: clinicians have no login yet.';
COMMENT ON COLUMN recovery_observations.corrects_observation_id IS
  'The version this row replaces. NULL for an original entry.';
