-- 0015_research: Nexivo M6. Research datasets and evaluation runs, kept apart
-- from clinical data: no foreign key to patients or users, and the clinical
-- tables never reference these. Only synthetic or de-identified research data
-- belongs here (spec Section 9: no real patient data).

CREATE TABLE research_datasets (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name               VARCHAR(100) NOT NULL,
  source             VARCHAR(10)  NOT NULL,
  seed               BIGINT,
  generator_options  JSONB,
  patient_count      INTEGER      NOT NULL,
  observation_count  INTEGER      NOT NULL,
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT research_datasets_source_check CHECK (source IN ('csv', 'synthetic')),
  CONSTRAINT research_datasets_seed_check CHECK ((source = 'synthetic') = (seed IS NOT NULL))
);

COMMENT ON TABLE research_datasets IS
  'Nexivo M6: an imported CSV or a seeded synthetic dataset. Isolated from clinical tables.';
COMMENT ON COLUMN research_datasets.seed IS 'Generator seed (synthetic only): the same seed and options give the same rows.';

CREATE TABLE research_observations (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id            BIGINT       NOT NULL,
  seq                   INTEGER      NOT NULL,
  patient_key           VARCHAR(100) NOT NULL,
  day_post_op           INTEGER      NOT NULL,
  pain                  SMALLINT     NOT NULL,
  mobility              SMALLINT     NOT NULL,
  fatigue               SMALLINT     NOT NULL,
  symptoms              JSONB        NOT NULL,
  doses_prescribed      INTEGER      NOT NULL,
  doses_taken           INTEGER      NOT NULL,
  milestones_completed  INTEGER      NOT NULL,
  milestones_due        INTEGER      NOT NULL,
  label                 VARCHAR(10)  NOT NULL,

  CONSTRAINT research_observations_seq_key UNIQUE (dataset_id, seq),
  CONSTRAINT research_observations_values_check CHECK (
    day_post_op BETWEEN 0 AND 365 AND pain BETWEEN 0 AND 10 AND mobility BETWEEN 0 AND 10 AND fatigue BETWEEN 0 AND 10
    AND doses_taken BETWEEN 0 AND doses_prescribed AND milestones_completed BETWEEN 0 AND milestones_due),
  CONSTRAINT research_observations_label_check CHECK (label IN ('normal', 'slower', 'attention')),
  CONSTRAINT research_observations_dataset_fkey FOREIGN KEY (dataset_id)
    REFERENCES research_datasets (id) ON DELETE CASCADE
);

COMMENT ON TABLE research_observations IS
  'Nexivo M6: dataset rows. patient_key is the dataset''s own id (not patients.id); label is the ground truth.';
COMMENT ON COLUMN research_observations.seq IS 'Row order in the dataset; breaks ties between rows on the same day.';

CREATE TABLE evaluation_runs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id  BIGINT      NOT NULL,
  config_id   BIGINT      NOT NULL,
  seed        BIGINT      NOT NULL,
  split       JSONB       NOT NULL,
  metrics     JSONB       NOT NULL,
  confusion   JSONB       NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT evaluation_runs_dataset_fkey FOREIGN KEY (dataset_id)
    REFERENCES research_datasets (id) ON DELETE CASCADE,
  CONSTRAINT evaluation_runs_config_fkey FOREIGN KEY (config_id)
    REFERENCES scoring_configs (id)
);

CREATE INDEX idx_evaluation_runs_dataset ON evaluation_runs (dataset_id);

COMMENT ON TABLE evaluation_runs IS
  'Nexivo M6: ReviveCare-style fixed-threshold baseline vs Nexivo, replayed without look-ahead. metrics: test-set results {baseline, nexivo} plus tuning-set results under "tuning".';
COMMENT ON COLUMN evaluation_runs.seed IS 'Seed of the patient split (30% tuning / 70% test).';
COMMENT ON COLUMN evaluation_runs.split IS '{tuning_fraction, tuning: [patient keys], test: [patient keys]}.';
