-- 0008_recovery_profiles: Nexivo M1. Surgery details for a patient, 1:1 with patients.
-- patients.info stays as it is (free text written by the doctor); this table holds
-- the structured fields the recovery score needs.

CREATE TABLE recovery_profiles (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id              BIGINT       NOT NULL,
  surgery_type            VARCHAR(100),
  surgery_date            DATE         NOT NULL,
  expected_recovery_days  INTEGER      NOT NULL DEFAULT 42,
  notes                   TEXT,
  created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT recovery_profiles_patient_id_key UNIQUE (patient_id),
  CONSTRAINT recovery_profiles_expected_recovery_days_check CHECK (expected_recovery_days BETWEEN 1 AND 365),
  CONSTRAINT recovery_profiles_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE
);

COMMENT ON TABLE recovery_profiles IS
  'Nexivo: surgery details per patient (one row each). surgery_date anchors day_post_op of every observation.';
COMMENT ON COLUMN recovery_profiles.expected_recovery_days IS
  'Day the expected recovery curve reaches its target. Defaults to the scoring config''s default_expected_recovery_days (42).';
COMMENT ON COLUMN recovery_profiles.surgery_date IS
  'Cannot change once observations exist: their stored day_post_op values depend on it.';
