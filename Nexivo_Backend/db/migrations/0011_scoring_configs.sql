-- 0011_scoring_configs: Nexivo M2. Versioned weights, thresholds and templates.
-- Every stored score will record the config row it was computed with.

CREATE TABLE scoring_configs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version     VARCHAR(50)  NOT NULL,
  params      JSONB        NOT NULL,
  active      BOOLEAN      NOT NULL DEFAULT false,
  created_by  BIGINT,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT scoring_configs_version_key UNIQUE (version),
  CONSTRAINT scoring_configs_params_check CHECK (jsonb_typeof(params) = 'object')
);

-- At most one active row; the seed below makes it exactly one.
CREATE UNIQUE INDEX scoring_configs_one_active ON scoring_configs (active) WHERE active;

COMMENT ON TABLE scoring_configs IS
  'Nexivo: versioned scoring parameters (spec Section 8). Rows are never edited: a change is a new version.';
COMMENT ON COLUMN scoring_configs.params IS
  'Spec Section 8 JSON without "version" (that is the version column), plus milestone_templates.';
COMMENT ON COLUMN scoring_configs.created_by IS
  'users.id of the author. No foreign key on purpose: TRUNCATE users CASCADE would wipe the configs (and their history) with it. NULL until admins can log in.';

