-- 0010_recovery_milestones: Nexivo M1. A patient's milestone plan and completion.

CREATE TABLE recovery_milestones (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id    BIGINT       NOT NULL,
  name          VARCHAR(200) NOT NULL,
  target_day    INTEGER      NOT NULL,
  completed_at  TIMESTAMPTZ,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT recovery_milestones_target_day_check CHECK (target_day BETWEEN 0 AND 365),
  CONSTRAINT recovery_milestones_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE
);

CREATE INDEX idx_recovery_milestones_patient ON recovery_milestones (patient_id, target_day);

COMMENT ON TABLE recovery_milestones IS
  'Nexivo: milestone plan. Created from the scoring config''s milestone_templates when a recovery profile is first saved; more can be added.';
COMMENT ON COLUMN recovery_milestones.target_day IS
  'Day post-op by which the milestone is due.';
