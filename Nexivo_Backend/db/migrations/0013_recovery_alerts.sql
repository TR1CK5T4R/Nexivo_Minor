-- 0013_recovery_alerts: Nexivo M3. Trend and anomaly alerts with a workflow
-- (open → acknowledged → resolved). One unresolved alert per patient + type +
-- parameter: when the same condition shows up again, the existing alert is
-- updated (details, last_seen_at) instead of a duplicate being created.

CREATE TABLE recovery_alerts (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id       BIGINT       NOT NULL,
  observation_id   BIGINT       NOT NULL,
  type             VARCHAR(30)  NOT NULL,
  parameter        VARCHAR(60),
  severity         VARCHAR(10)  NOT NULL,
  message          TEXT         NOT NULL,
  details          JSONB        NOT NULL DEFAULT '{}',
  status           VARCHAR(15)  NOT NULL DEFAULT 'open',
  acknowledged_by  BIGINT,
  acknowledged_at  TIMESTAMPTZ,
  resolved_at      TIMESTAMPTZ,
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_seen_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT recovery_alerts_type_check CHECK (type IN (
    'SUDDEN_DETERIORATION', 'SCORE_DROP', 'UNUSUAL_CHANGE', 'NO_IMPROVEMENT', 'ADHERENCE_DROP', 'MILESTONE_OVERDUE')),
  CONSTRAINT recovery_alerts_severity_check CHECK (severity IN ('low', 'medium', 'high')),
  CONSTRAINT recovery_alerts_status_check CHECK (status IN ('open', 'acknowledged', 'resolved')),
  CONSTRAINT recovery_alerts_details_check CHECK (jsonb_typeof(details) = 'object'),
  CONSTRAINT recovery_alerts_patient_fkey FOREIGN KEY (patient_id)
    REFERENCES patients (id) ON DELETE CASCADE,
  CONSTRAINT recovery_alerts_observation_fkey FOREIGN KEY (observation_id)
    REFERENCES recovery_observations (id) ON DELETE CASCADE,
  CONSTRAINT recovery_alerts_acknowledged_by_fkey FOREIGN KEY (acknowledged_by)
    REFERENCES users (id) ON DELETE SET NULL
);

-- De-duplication: at most one unresolved alert per patient + type + parameter.
-- The upsert targets this index, so two concurrent check-ins can't both insert.
CREATE UNIQUE INDEX recovery_alerts_one_unresolved
  ON recovery_alerts (patient_id, type, (COALESCE(parameter, '')))
  WHERE status <> 'resolved';

CREATE INDEX idx_recovery_alerts_patient ON recovery_alerts (patient_id, status, last_seen_at DESC);

COMMENT ON TABLE recovery_alerts IS
  'Nexivo: in-app trend and anomaly alerts (never emailed). Unresolved alerts are de-duplicated per patient + type + parameter.';
COMMENT ON COLUMN recovery_alerts.observation_id IS 'The check-in that first raised the alert; details hold the latest values.';
COMMENT ON COLUMN recovery_alerts.parameter IS
  'pain | mobility | fatigue | symptoms | adherence, symptoms.<name>, milestones.<id>, or NULL (SCORE_DROP, ADHERENCE_DROP).';
COMMENT ON COLUMN recovery_alerts.severity IS 'Latest severity: ADHERENCE_DROP can move between medium and high as adherence changes.';
COMMENT ON COLUMN recovery_alerts.acknowledged_by IS 'users.id of the patient who acknowledged it; NULL for clinicians (no login yet).';
